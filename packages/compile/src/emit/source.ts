/**
 * The emitted-code printer (`WP-120-08`).
 *
 * Why a printer at all, rather than template strings: every rule in this file's neighbourhood is a rule about
 * *bytes*. `IMPL-120-R022` wants byte-identical rebuilds, `REPO-R015` bans the six sources of nondeterminism,
 * and `CMP-R013` fixes the first five lines of every file. A `join('\n')` scattered through four emitters gets
 * one of those wrong — usually by letting an array's insertion order reach the output — and no test notices
 * until a diff job fails on a maintainer's machine. So indentation, line breaks, key order and literal spelling
 * all live here, once, and the emitters below describe *structure*.
 *
 * Nothing here reads the clock, the environment, or a path (`IMPL-120-R001`): the header takes the tool
 * version and input hash as parameters, because a header that called `Date.now()` would break the double-build
 * gate `T-CMP-003` in the one place least likely to be tested.
 */

/** A piece of emitted source. `string`s are leaves; arrays nest, and an object adds one indent level. */
export type Chunk = string | readonly Chunk[] | { readonly indent?: number; readonly lines?: readonly Chunk[] };

const INDENT = '  ';

function flatten(chunk: Chunk, depth: number, out: string[]): void {
  if (typeof chunk === 'string') {
    out.push(...chunk.split('\n').map((line) => (line === '' ? '' : INDENT.repeat(depth) + line)));
    return;
  }
  if (!Array.isArray(chunk) && 'lines' in chunk) {
    for (const line of chunk.lines ?? []) flatten(line, depth + (chunk.indent ?? 1), out);
    return;
  }
  if (Array.isArray(chunk)) for (const child of chunk) flatten(child, depth, out);
}

/** Renders a chunk tree to text with two-space indentation, ending in exactly one newline. */
export function render(chunk: Chunk): string {
  const out: string[] = [];
  flatten(chunk, 0, out);
  const text = out.join('\n').replace(/\n{3,}/g, '\n\n');
  return text.endsWith('\n') ? text : `${text}\n`;
}

/** `REPO-R015`: an emitted path is relative to the project root and always uses forward slashes. */
export function emittedPath(...parts: readonly string[]): string {
  return parts
    .map((part) => part.replace(/\\/g, '/').replace(/^\/+|\/+$/g, ''))
    .filter((part) => part !== '' && part !== '.')
    .join('/');
}

/**
 * `CMP-R013`'s generated header, verbatim in field order.
 *
 * It carries **no** suppression. A generated file that disables the emitted project's own rules would let the
 * emitter break `IMPL-120-R014`'s bans by writing them off, and the ban list would then be decoration; so the
 * printer's job is to emit code that passes the config `emit/scaffold.ts` writes, not to switch it down. Where
 * a suppression is genuinely unavoidable it is written inline, next to the line it excuses, and it is a
 * decision the report carries (`IMPL-120-R013`).
 */
export function generatedHeader(input: {
  readonly toolVersion: string;
  readonly inputName: string;
  readonly sha256: string;
  readonly movie: string;
  readonly timeline: string;
}): string {
  const sha = input.sha256.slice(0, 4);
  return [
    `// AUTO-GENERATED by swf-forge ${input.toolVersion} — DO NOT EDIT.`,
    `// Source: ${input.inputName} (sha256:${sha}…)  Movie: ${input.movie}  Timeline: ${input.timeline}`,
    `// Regenerate: npx swfforge build ${input.inputName} --out .`,
    '// Manual edits are overwritten. To patch behaviour, use swf-forge.overrides.ts (CMP-§9.5).',
  ].join('\n');
}

/**
 * `REPO-R015`'s number rule. `String(1e21)` is `1e+21`, which is valid TypeScript, so decimal formatting can
 * go through `Number.prototype.toString(10)` — but only for the three values whose spelling is either a global
 * (`NaN`, `Infinity`) or a sign that JSON and `toString` disagree about (`-0`), and those are written
 * explicitly because an emitted `NaN` identifier is a runtime global read and `-0` would fold to `0` in a
 * source map consumer.
 */
export function formatNumber(value: number): string {
  if (Number.isNaN(value)) return 'Number.NaN';
  if (value === Number.POSITIVE_INFINITY) return 'Number.POSITIVE_INFINITY';
  if (value === Number.NEGATIVE_INFINITY) return 'Number.NEGATIVE_INFINITY';
  if (value === 0 && Object.is(value, -0)) return '-0';
  return value.toString(10);
}

/**
 * A string literal that survives every byte an SWF can carry. `JSON.stringify` handles the escapes and (since
 * ES2019) the two line separators that are valid in a JSON string but not in an ECMAScript one; the only extra
 * step is `U+0000`, which is legal inside a template but not inside a `\'…\'` for every tool in the chain, so
 * it is written as an escape.
 */
export function formatString(value: string): string {
  return JSON.stringify(value).replace(/\u0000/g, '\\u0000');
}

/** A `Uint8Array` literal, in fixed 16-byte rows so a blob diff is line-stable (`IMPL-120-R018`). */
export function formatBytes(bytes: readonly number[]): string {
  if (bytes.length === 0) return 'Uint8Array.of()';
  const rows: string[] = [];
  for (let i = 0; i < bytes.length; i += 16) {
    rows.push(
      bytes
        .slice(i, i + 16)
        .map((byte) => `0x${byte.toString(16).padStart(2, '0')}`)
        .join(', '),
    );
  }
  if (rows.length === 1) return `Uint8Array.of(${rows[0] ?? ''})`;
  return `Uint8Array.of(\n${rows.map((row) => `  ${row},`).join('\n')}\n)`;
}

/** One `key: value` entry, with `undefined` fields dropped rather than written (`exactOptionalPropertyTypes`). */
export function objectLiteral(entries: readonly (readonly [string, string | null])[]): string {
  const kept = entries.filter(([, value]) => value !== null);
  if (kept.length === 0) return '{}';
  if (kept.length <= 3 && kept.every(([, value]) => (value ?? '').length < 24)) {
    return `{ ${kept.map(([key, value]) => `${key}: ${value}`).join(', ')} }`;
  }
  return `{\n${kept.map(([key, value]) => `  ${key}: ${value},`).join('\n')}\n}`;
}

/**
 * The one-line form of an object literal. Placement and handler entries nest inside a data row, where a nested
 * literal's own newlines cannot inherit the outer indent — the result is a row that looks mis-indented in an
 * editor and diff noise on every unrelated change to a neighbouring field. Data rows stay one line each.
 */
export function objectLiteralInline(entries: readonly (readonly [string, string | null])[]): string {
  const kept = entries.filter(([, value]) => value !== null && value !== undefined);
  if (kept.length === 0) return '{}';
  return `{ ${kept.map(([key, value]) => `${propertyKey(key)}: ${value}`).join(', ')} }`;
}

/** A valid identifier per `IMPL-120-R033`'s alphabet, quoted when it is not one. */
export function propertyKey(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : formatString(name);
}

/**
 * An exported function with the context parameters `IMPL-120-R017` and `AVM1-R035` require. `docs` are the
 * provenance comments the `porting-notes.json` report cross-references (`CMP-R030`): the block id and the byte
 * range it came from, so a reader can find the opcode that produced a line without a source map.
 */
export function emittedFunction(input: {
  readonly name: string;
  readonly params: readonly string[];
  readonly returns: string | null;
  readonly body: readonly Chunk[];
  readonly docs?: readonly string[];
  readonly exported?: boolean;
}): string {
  const head = input.docs?.length ? [`/** ${input.docs.join(' · ')} */`] : [];
  const signature = `${input.exported === false ? '' : 'export function '}${input.name}(${input.params.join(', ')})${
    input.returns === null ? ': void' : `: ${input.returns}`
  } {`;
  const body = input.body.length > 0 ? input.body : ['// (no operations)'];
  return render([...head, signature, { lines: body }, '}']);
}

/** A `const` table sorted by key, because `REPO-R016` requires manifest keys lexicographic. */
export function sortedTable(
  name: string,
  type: string,
  entries: ReadonlyMap<string, string>,
  kind: 'Record' | 'array' = 'Record',
): string {
  const keys = [...entries.keys()].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  if (kind === 'array') {
    const items = keys.map((key) => entries.get(key) as string);
    return `export const ${name}: readonly ${type}[] = ${items.length === 0 ? '[]' : `[\n${items.map((item) => `  ${item},`).join('\n')}\n]`};`;
  }
  const body = keys.map((key) => `  ${propertyKey(key)}: ${entries.get(key) as string},`);
  return `export const ${name}: Readonly<Record<string, ${type}>> = ${
    body.length === 0 ? '{}' : `{\n${body.join('\n')}\n}`
  };`;
}
